#!/usr/bin/env node
// Generates packages/shared/src/abi.ts from the Foundry build artifacts.
// Usage: (cd contracts && forge build) && node scripts/gen-shared-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = (file, name) =>
  JSON.parse(readFileSync(join(root, "contracts", "out", file, `${name}.json`), "utf8"));

const escrow = artifact("EverpieceEscrow.sol", "EverpieceEscrow");
const ausd = artifact("IAUSD.sol", "IAUSD");
const pay = artifact("EverpiecePay.sol", "EverpiecePay");
const agoraPair = artifact("IAgoraStableSwapPair.sol", "IAgoraStableSwapPair");
const agoraWhitelister = artifact("IAgoraStableSwapPair.sol", "IAgoraTestnetWhitelister");
const earn = artifact("EverpieceEarn.sol", "EverpieceEarn");
const erc4626 = artifact("IERC4626.sol", "IERC4626");

const header = `// GENERATED by scripts/gen-shared-abi.mjs from contracts/out — do not edit by hand.
// Source: contracts/src/EverpieceEscrow.sol (ESCROW_SPEC v0.2), EverpiecePay.sol, EverpieceEarn.sol, interfaces/IAUSD.sol, interfaces/IAgoraStableSwapPair.sol
`;
const body =
  `export const everpieceEscrowAbi = ${JSON.stringify(escrow.abi, null, 2)} as const;\n\n` +
  `/** Subset of Monad AUSD used by Everpiece (docs/VERIFIED.md §2). */\n` +
  `export const ausdAbi = ${JSON.stringify(ausd.abi, null, 2)} as const;\n\n` +
  `export const everpiecePayAbi = ${JSON.stringify(pay.abi, null, 2)} as const;\n\n` +
  `/** The documented subset of Agora's AgoraStableSwapPair (docs/INTEGRATION_VERIFICATION.md). */\n` +
  `export const agoraPairAbi = ${JSON.stringify(agoraPair.abi, null, 2)} as const;\n\n` +
  `export const agoraWhitelisterAbi = ${JSON.stringify(agoraWhitelister.abi, null, 2)} as const;\n\n` +
  `export const everpieceEarnAbi = ${JSON.stringify(earn.abi, null, 2)} as const;\n\n` +
  `/** OpenZeppelin IERC4626 (the Earn vaults: Aave waMonAUSD on mainnet, TestYieldVault on testnet). */\n` +
  `export const erc4626Abi = ${JSON.stringify(erc4626.abi, null, 2)} as const;\n`;

writeFileSync(join(root, "packages", "shared", "src", "abi.ts"), header + "\n" + body);
console.log(`abi.ts written: escrow ${escrow.abi.length}, ausd ${ausd.abi.length}, pay ${pay.abi.length}, agora pair ${agoraPair.abi.length} entries`);
